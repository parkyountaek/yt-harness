# A sub-session runs exactly one plugin, its harness, with that plugin's hooks on
# (hooks/hooks.json, generated by yt-build: work order context, yt-guard, and the stop
# gate). The human's own hooks, plugins, and interface mods (mods/) stay out, for both
# runtimes: they belong to the human's setup (e.g. a terminal app rewrites them), would
# run in one runtime only, and are not part of any work order. Hooks run inside the sandbox.
#
# Claude: user settings are not loaded (--setting-sources project,local). From them only
# what the runtime needs to start is carried over through --settings.
CLAUDE_CARRY = ("model", "apiKeyHelper", "env")
CLAUDE_DROP_ENV = ("CLAUDE_CODE_PLUGIN_DIRS", "CLAUDE_MODS_THEME_FILE")


def claude_isolation(home=None):
    user = core.read_json(os.path.join(home or core.HOME, ".claude", "settings.json"), {}) or {}
    settings = {k: user[k] for k in CLAUDE_CARRY if k in user}
    env = {k: v for k, v in (settings.pop("env", None) or {}).items() if k not in CLAUDE_DROP_ENV}
    if env:
        settings["env"] = env
    settings["skipDangerousModePermissionPrompt"] = True
    return ["--setting-sources", "project,local", "--settings", json.dumps(settings, sort_keys=True)]


EVENT_KEYS = {"PreToolUse": "pre_tool_use", "PostToolUse": "post_tool_use", "PermissionRequest": "permission_request",
              "SessionStart": "session_start", "SessionEnd": "session_end", "UserPromptSubmit": "user_prompt_submit",
              "Stop": "stop", "SubagentStart": "subagent_start", "SubagentStop": "subagent_stop",
              "PreCompact": "pre_compact", "PostCompact": "post_compact", "Notification": "notification",
              "Interrupt": "interrupt"}


def _snake(event):
    return EVENT_KEYS.get(event) or re.sub(r"(?<!^)(?=[A-Z])", "_", event).lower()


def codex_isolation(harness, home=None):
    """Codex: hooks on without the trust prompt (only the harness's hooks are enabled), every
    user-level hook turned off by its state key, and every other plugin turned off."""
    home = home or core.HOME
    config = parity.codex_config(home)
    codex_home = parity._codex_home(home)
    sources = [(os.path.join(codex_home, "hooks.json"),
                (core.read_json(os.path.join(codex_home, "hooks.json"), {}) or {}).get("hooks") or {}),
               (os.path.join(codex_home, "config.toml"),
                {k: v for k, v in (config.get("hooks") or {}).items() if k != "state"})]
    off = []
    for path, events in sources:
        for event, groups in events.items():
            for g, group in enumerate(groups if isinstance(groups, list) else []):
                for h, _ in enumerate((group or {}).get("hooks") or []):
                    off.append(f"{path}:{_snake(event)}:{g}:{h}")
    # The harness's own hooks are named on, so a human's features.hooks=false or a stale
    # per-hook state cannot drop them (-c values merge into the user's config).
    on = []
    with open(os.path.join(core.harness_dir(harness), "hooks", "hooks.json"), encoding="utf-8") as f:
        for event, groups in (json.load(f).get("hooks") or {}).items():
            for g, group in enumerate(groups):
                for h, _ in enumerate(group.get("hooks") or []):
                    on.append(f"{harness}@yt-harness:hooks/hooks.json:{_snake(event)}:{g}:{h}")
    state = [f"{json.dumps(k)}={{enabled=false}}" for k in off] + [f"{json.dumps(k)}={{enabled=true}}" for k in on]
    flags = ["--dangerously-bypass-hook-trust", "-c", "features.hooks=true", "-c", "hooks.state={" + ",".join(state) + "}"]
    # One inline table names every plugin, so it reads the same whether -c merges or replaces.
    mine = f"{harness}@yt-harness"
    names = sorted(set(config.get("plugins") or {}) | {mine})
    return flags + ["-c", "plugins={" + ",".join(f"{json.dumps(n)}={{enabled={'true' if n == mine else 'false'}}}"
                                                 for n in names) + "}"]


# MCP servers and connectors (Gmail, Drive, Slack, Trello, ...) are off in every
# sub-session: they are channels that move task data to outside services. Claude:
# --strict-mcp-config with no --mcp-config, plus ENABLE_CLAUDEAI_MCP_SERVERS=false in
# session_env for the claude.ai connectors. Codex: apps off, every configured server off.
CLAUDE_NO_MCP = ["--strict-mcp-config"]


def codex_no_mcp():
    flags = ["-c", "features.apps=false"]
    for name in sorted((parity.codex_config().get("mcp_servers") or {})):
        flags += ["-c", f"mcp_servers.{name}.enabled=false"]
    return flags


ANSWER_PROMPT = ("The human answered your question: {answer}\n"
                 "Run `yt-status running`, then continue the work order in {task_dir}/TASK.md.")


EFFORTS = {"claude": ("low", "medium", "high", "xhigh", "max"),
           "codex": ("low", "medium", "high", "xhigh", "max", "ultra")}
MODEL_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*(\[1m\])?")   # e.g. opus[1m]: Claude's 1M context


def workspace(cwd=None):
    """The project the coordinator runs in: the git root above cwd, else cwd itself."""
    path = os.path.realpath(cwd or os.getcwd())
    probe = path
    while True:
        if os.path.exists(os.path.join(probe, ".git")):
            return probe
        parent = os.path.dirname(probe)
        if parent == probe:
            return path
        probe = parent


def saved_models(ws=None):
    """The human's model choices for a workspace (~/yt-local/config.json
    "models" {workspace: {harness: {runtime: {model, effort}}}})."""
    return ((core.read_json(core.CONFIG, {}) or {}).get("models") or {}).get(ws or workspace()) or {}


def save_model(harness_name, runtime, model, effort=None, ws=None):
    """Save (or with model None, forget) the choice for a harness and runtime in a workspace."""
    check_model(model, effort, runtime)
    with core.locked(core.CONFIG + ".lock"):
        config = core.read_json(core.CONFIG, {}) or {}
        per = config.setdefault("models", {}).setdefault(ws or workspace(), {}).setdefault(harness_name, {})
        if model:
            per[runtime] = {"model": model, **({"effort": effort} if effort else {})}
        else:
            per.pop(runtime, None)
        core.write_json_atomic(core.CONFIG, config)


def check_model(model, effort, runtime):
    if model and not MODEL_NAME.fullmatch(str(model)):
        raise ValueError(f"bad model name {model!r}")
    if effort and effort not in EFFORTS[runtime]:
        raise ValueError(f"bad effort {effort!r} for {runtime}; use one of {', '.join(EFFORTS[runtime])}")


def pick_model(harness_name, runtime, model=None, effort=None):
    """(model, effort) for a run: the yt-spawn flags, else the human's saved choice for the
    harness in this workspace (yt model), else None (the runtime's own default)."""
    saved = saved_models().get(harness_name, {}).get(runtime) or {}
    model, effort = model or saved.get("model"), effort or saved.get("effort")
    check_model(model, effort, runtime)
    return model, effort


