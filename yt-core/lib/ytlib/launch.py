def runtime_argv(runtime, harness, out_dir, session_id, prompt, resume=False, interactive=True,
                 model=None, effort=None):
    """Command line for one run. interactive=False is print/exec mode (headless runner)."""
    harness_path = core.harness_dir(harness)
    if runtime == "claude":
        sid = ["--resume", session_id] if resume else ["--session-id", session_id]
        pick = [*(["--model", model] if model else []), *(["--effort", effort] if effort else [])]
        return ["claude", *([] if interactive else ["-p"]), "--plugin-dir", harness_path, *claude_isolation(),
                *CLAUDE_NO_MCP, *pick, *sid, "--dangerously-skip-permissions", prompt]
    # Codex: the shared sandbox is the enforcement layer, so Codex's own sandbox is off
    # (the two cannot be nested). The harness plugin is installed disabled and enabled per run.
    if "." in out_dir:
        # Codex splits -c keys on dots, so the trust key would be misread.
        raise RuntimeError(f"task folder path must not contain '.': {out_dir}")
    flags = [*codex_isolation(harness), *codex_no_mcp(), "-c", f"projects.{out_dir}.trust_level=trusted"]
    flags += [*(["-c", f'model="{model}"'] if model else []),
              *(["-c", f'model_reasoning_effort="{effort}"'] if effort else [])]
    if not interactive:
        # exec and exec resume take the same settings as -c values.
        flags += ["-c", 'sandbox_mode="danger-full-access"', "-c", 'approval_policy="never"', "--skip-git-repo-check"]
        return ["codex", "exec", *(["resume"] if resume else []), *flags, *([session_id] if resume else []), prompt]
    flags += ["--sandbox", "danger-full-access", "--ask-for-approval", "never"]
    if resume:
        return ["codex", "resume", *flags, session_id, prompt]
    return ["codex", *flags, prompt]


# The only variables a sub-session inherits. Anything else (coordinator session ids,
# messaging sockets and tokens, terminal-app hook tokens) would leak the coordinator
# into the sub-session and make the two runtimes see different environments.
PASS_ENV = ("HOME", "USER", "LOGNAME", "SHELL", "LANG", "TZ", "CODEX_HOME")
PASS_ENV_PREFIX = ("LC_",)


def session_env(task_dir, tmp_dir):
    """The complete environment of a sub-session; identical for every runtime."""
    extra = (core.read_json(core.CONFIG, {}) or {}).get("envPassthrough", [])
    env = {k: v for k, v in os.environ.items()
           if k in PASS_ENV or k.startswith(PASS_ENV_PREFIX) or k in extra}
    py_bin = os.path.dirname(os.path.realpath(sys.executable))
    env.update({
        "YT_TASK_DIR": task_dir,
        "YT_CORE": core.CORE,   # harness hooks run yt-core/bin/yt-hook and yt-guard from here
        "TMPDIR": tmp_dir + "/",
        "CLAUDE_CODE_TMPDIR": tmp_dir,   # Claude's Bash tool keeps its cwd file here, not in /tmp
        "ENABLE_CLAUDEAI_MCP_SERVERS": "false",   # no claude.ai connectors (see CLAUDE_NO_MCP)
        # The sandbox hides ~/.gitconfig, and git treats an unreadable global config as fatal.
        # Identity for commits is written into a task clone's own config (gitwork.prepare).
        "GIT_CONFIG_GLOBAL": os.devnull,
        # zsh makes here-document temp files under $TMPPREFIX (default /tmp/zsh), not $TMPDIR.
        "TMPPREFIX": os.path.join(tmp_dir, "zsh"),
        "PATH": os.pathsep.join([os.path.join(core.CORE, "bin"), py_bin, os.environ.get("PATH", "")]),
    })
    return env


RUNTIME_CONFIG = (".claude", ".codex")


def clear_runtime_config(out_dir, tmp_dir):
    """out/ is the session's working directory and writable, so a session could leave project
    settings there (hooks, plugins) for its next start. Move them aside before every start."""
    moved = []
    for name in RUNTIME_CONFIG:
        path = os.path.join(out_dir, name)
        if os.path.lexists(path):
            dest = os.path.join(tmp_dir, f"set-aside-{int(time.time())}-{name.lstrip('.')}")
            os.makedirs(tmp_dir, exist_ok=True)
            os.rename(path, dest)
            moved.append(name)
    if moved:
        core.log_event("runtime-config-set-aside", names=moved)
    return moved


STARTUP_GRACE = 4  # seconds a runtime must stay alive to count as started


def codex_plugin_problem(harness_name, version):
    """Codex runs an installed copy of the harness plugin; it must exist and match the source."""
    cache = os.path.join(core.HOME, ".codex", "plugins", "cache", "yt-harness", harness_name)
    if not os.path.isdir(cache):
        return f"Codex does not have {harness_name} installed; run yt-core/bin/yt-setup"
    if version and not os.path.isdir(os.path.join(cache, str(version))):
        return f"Codex has an old copy of {harness_name} (want {version}); run yt-core/bin/yt-setup"
    return None


def confirm_started(runner, handle):
    """A runner can start a terminal whose runtime exits at once; require it to stay up.

    A headless run may finish within the grace period; then it must have exited 0.
    """
    end = time.time() + STARTUP_GRACE
    while time.time() < end:
        if not runner.alive(handle):
            break
        time.sleep(0.5)
    if runner.alive(handle):
        return True
    return getattr(runner, "INTERACTIVE", True) is False and runner.exit_code(handle) == 0


def find_codex_session(out_dir, since, timeout=30, scan=20):
    """Codex cannot preset a session id; read it from the rollout file whose cwd is out_dir."""
    root = os.path.join(core.HOME, ".codex", "sessions")
    end = time.time() + timeout
    while time.time() < end:
        paths = sorted(glob.glob(os.path.join(root, "*", "*", "*", "*.jsonl")), key=os.path.getmtime, reverse=True)
        for path in paths[:scan]:
            if os.path.getmtime(path) < since:
                break
            try:
                with open(path, encoding="utf-8") as f:
                    meta = json.loads(f.readline())
            except (OSError, ValueError):
                continue
            payload = meta.get("payload", {})
            if meta.get("type") == "session_meta" and payload.get("cwd") == out_dir:
                return payload.get("id")
        time.sleep(1)
    return None


def start(task_id, harness_name, harness, runtime, runner_name, session_id, resume=False, answer=None,
          vault=None, repo_source=None, repo_clone=None, model=None, effort=None):
    """Wrap the runtime in the shared sandbox and start it with the runner. Returns (handle, session_id).

    answer: resume with the human's answer as the prompt (headless runner).
    """
    plat = ytplatform.load()
    runner = runners.load(runner_name)
    task_dir = core.task_dir(task_id)
    out_dir = os.path.join(task_dir, "out")
    if answer is not None:
        prompt = ANSWER_PROMPT.format(answer=answer, task_dir=task_dir)
    else:
        prompt = (RESUME_PROMPT if resume else START_PROMPT).format(task_dir=task_dir)
    interactive = getattr(runner, "INTERACTIVE", True)
    cmd = runtime_argv(runtime, harness_name, out_dir, session_id, prompt, resume, interactive, model, effort)
    policy = core.resolve_policy(harness, task_dir, vault, repo_clone)
    # The session also needs to read yt-core (for yt-status), the harness, and the Python install.
    extra_read = [core.CORE, core.harness_dir(harness_name), os.path.realpath(sys.base_prefix)]
    # yt-mask reuses the repo guard's patterns and the local blocked terms (read-only).
    extra_read += [p for p in (os.path.join(core.REPO, ".githooks"), os.path.join(core.LOCAL, "blocked-terms.txt"))
                   if os.path.exists(p)]
    # A --shared clone reads the source's objects through alternates (read-only).
    if repo_source:
        extra_read.append(os.path.join(repo_source, ".git", "objects"))
    tmp_dir = os.path.join(task_dir, "tmp")
    os.makedirs(tmp_dir, exist_ok=True)
    clear_runtime_config(out_dir, tmp_dir)
    if runtime == "claude":
        # Claude makes a --plugin-dir plugin's data folder before it runs the plugin's hooks;
        # the sandbox cannot create it under ~/.claude, so it is made here (it stays empty).
        os.makedirs(os.path.join(core.HOME, ".claude", "plugins", "data", f"{harness_name}-inline"), exist_ok=True)
    wrapped = plat.sandbox_argv(policy, runtime, cmd, profile_dir=task_dir, extra_read=extra_read,
                                tmp_dir=tmp_dir, cwd=out_dir)
    env = session_env(task_dir, tmp_dir)
    since = time.time() - 1
    handle = runner.spawn(task_id, out_dir, wrapped, env)
    if not confirm_started(runner, handle):
        raise RuntimeError(f"{runtime} exited during startup (runner handle {handle})")
    if runtime == "codex" and not session_id:
        session_id = find_codex_session(out_dir, since)
    return handle, session_id
